const dict = { en, hi, pa };

const Ctx = createContext({ lang: 'en', setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, setLang] = useState('en');
  const t = (key, vars) => {
    let s = dict[lang][key] ?? dict.en[key] ?? key;
    if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replace(`{${k}}`, String(v)); });
    return s;
  };
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);

export function LanguagePill({ style }) {
  const { lang, setLang } = useLang();
  return (
    <View style={[pillStyles.wrap, style]}>
      {LANGS.map((l) => (
        <TouchableOpacity key={l.code} onPress={() => setLang(l.code)} style={[pillStyles.btn, lang === l.code && pillStyles.btnActive]}>
          <Text style={{ fontSize: 10.5, fontWeight: '800', color: lang === l.code ? '#fff' : C.onSurfaceVariant }}>{l.label}</Text>
        </TouchableOpacity>
      ))}
    </View>
  );
}

